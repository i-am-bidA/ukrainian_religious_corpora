# === Функція підрахунку речень ===
def count_sentences(text):
    # === Попередня обробка ===

    # 1. Склеюємо слова, розірвані дефісом і переносом
    text = re.sub(r'(\w+)-\s*\n\s*(\w+)', r'\1\2', text)

    # 2. Прибираємо всі переноси рядків
    text = re.sub(r'\n+', ' ', text)

    # 3. Видаляємо цифри
    text = re.sub(r'\d+', '', text)

    # 4. Прибираємо некириличні символи (включаючи латинку, грецькі тощо)
    text = re.sub(r'[^\u0400-\u04FF.,!?;:()\[\]«»"\s]', ' ', text)

    # 5. Уніфікуємо пробіли
    text = re.sub(r'\s{2,}', ' ', text).strip()
    # print(text)

    # Замінюємо крапки в скороченнях на спецсимвол, щоб не рахувати їх як кінець речення
    for abbr in abbreviation_expansion:
        text = text.replace(abbr, abbr.replace('.', '∯'))

    # Замінюємо ініціали типу "М." на "М∯"
    text = re.sub(r'\b[А-ЯҐЄІЇ]\.', lambda m: m.group().replace('.', '∯'), text)

    # Тепер безпечно розбиваємо текст на речення
    sentences = re.split(r'(?<=[.!?])\s+(?=[А-ЯҐЄІЇ])', text)
    # print(sentences)
    
    # Повертаємо кількість після відновлення крапок
    return sum(1 for s in sentences if s.strip())

#Основна функція
def calculate(file_names, name):
    combined = 0
    for file_name in file_names:
        file_path = os.path.join(folder_path, file_name)
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                content = f.read()
            num_sentences = count_sentences(content)
            print(f"{file_name}: {num_sentences} речень")
            combined += num_sentences
        except FileNotFoundError:
            print(f"{file_name}: файл не знайдено.")
        except Exception as e:
            print(f"{file_name}: помилка — {e}")
    print(f"\nУ файлах {name} всього {combined} речень.\n")

calculate(file_names_pcu, "ПЦУ")
calculate(file_names_upc, "УПЦ")
